// node tools/cover-icons.mjs            (from the repo root; network the first time)
// node tools/cover-icons.mjs --check    (writes nothing: the committed file must equal a fresh build)
// 09 Cover, E16 Part 5 (plan §8, owner Q-4): the Tabler filled icons, MIT.
//   - one pinned version (VERSION), the npm tarball checked against its sha512 (INTEGRITY);
//   - every filled icon except the "Brand" category (company logos are trademarks, not free art);
//   - each icon keeps Tabler's own path strings, unchanged (24 × 24 units), one string per <path>;
//   - search words: the name, the category and Tabler's tags.
// Writes js/cover/icon-set.js (loaded by the editor only when needed; never from a CDN at run time).
// The tarball is cached in tests/browser/.cache/ (git-ignored).
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const VERSION = '3.49.0';
const INTEGRITY = 'sha512-l+GnSkFETx0U26icxv1VUFnxxiTqXfCcVRiRAnyMwibupM2S2L/hSaZ9gmSgz01rkrsH/93NvLsxykqdanc6lw==';
const URL_ = `https://registry.npmjs.org/@tabler/icons/-/icons-${VERSION}.tgz`;
const DROP = ['Brand'];

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CACHE = path.join(REPO, 'tests/browser/.cache');
const TGZ = path.join(CACHE, `tabler-icons-${VERSION}.tgz`);
const OUT = path.join(REPO, 'js/cover/icon-set.js');
const check = process.argv.includes('--check');

fs.mkdirSync(CACHE, { recursive: true });
if (!fs.existsSync(TGZ)) {
  const r = await fetch(URL_);
  if (!r.ok) throw new Error(`${URL_}: HTTP ${r.status}`);
  fs.writeFileSync(TGZ, Buffer.from(await r.arrayBuffer()));
}
const tgz = fs.readFileSync(TGZ);
const got = 'sha512-' + crypto.createHash('sha512').update(tgz).digest('base64');
if (got !== INTEGRITY) { fs.rmSync(TGZ); throw new Error(`tabler tarball integrity ${got} ≠ ${INTEGRITY}`); }

const dir = fs.mkdtempSync(path.join(CACHE, 'tabler-'));
try {
  execFileSync('tar', ['-xzf', TGZ, '-C', dir, 'package/tabler-nodes-filled.json', 'package/icons.json', 'package/package.json', 'package/LICENSE']);
  const P = (f) => JSON.parse(fs.readFileSync(path.join(dir, 'package', f), 'utf8'));
  const pkg = P('package.json'), nodes = P('tabler-nodes-filled.json'), meta = P('icons.json');
  if (pkg.version !== VERSION || pkg.license !== 'MIT') throw new Error(`package ${pkg.version} ${pkg.license}`);
  const lic = fs.readFileSync(path.join(dir, 'package/LICENSE'), 'utf8');
  if (!/^MIT License/.test(lic)) throw new Error('LICENSE is not MIT');

  const rows = [];
  let dropped = 0;
  for (const name of Object.keys(nodes).sort()) {
    const m = meta[name] || {};
    const cat = m.category || 'Other';
    if (DROP.includes(cat) || /^brand-/.test(name)) { dropped++; continue; }
    const paths = nodes[name].map(([tag, a]) => {
      if (tag !== 'path' || typeof a.d !== 'string') throw new Error(`${name}: a ${tag}, not a path`);
      if (a.fill && a.fill !== 'currentColor') throw new Error(`${name}: fill ${a.fill}`);
      return a.d;
    });
    const tags = (m.tags || []).map(String).filter((t) => !name.split('-').includes(t)).join(' ');
    rows.push([name, cat, tags, paths]);
  }

  const body = rows.map((r) => '    ' + JSON.stringify(r)).join(',\n');
  const out = `/* ═══════════════════════════════════════════════════
   NicheInk · 09 Cover: the icon set (E16 Part 5, plan §8, owner Q-4)
   /js/cover/icon-set.js   (generated by tools/cover-icons.mjs; do not edit)

   Tabler Icons ${VERSION}, the filled style. MIT License, Copyright (c) 2020-2026
   Paweł Kuna (full text in THIRD-PARTY-NOTICES.md). Source: the npm package
   @tabler/icons ${VERSION}, ${INTEGRITY.slice(0, 22)}… (sha512).
   ${rows.length} icons: every filled icon except the ${dropped} in the "Brand" category
   (company logos are trademarks). Each row: [name, category, tags, paths];
   the paths are Tabler's own strings, unchanged, in a 24 × 24 box, each one
   filled on its own (non-zero), as the SVG draws them.

   kdpCover.iconSet = { version, rows }
   ═══════════════════════════════════════════════════ */
(function (root) {
  'use strict';
  const C = (root.kdpCover = root.kdpCover || {});
  C.iconSet = { version: '${VERSION}', rows: [
${body}
  ] };
})(globalThis);
`;
  if (check) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== out) { console.log('icon-set.js differs from a fresh build'); process.exit(1); }
    console.log(`cover icons ok: Tabler ${VERSION}, ${rows.length} icons (${dropped} brand icons left out), ${Buffer.byteLength(out)} bytes`);
  } else {
    fs.writeFileSync(OUT, out);
    console.log(`wrote ${path.relative(REPO, OUT)}: ${rows.length} icons, ${dropped} left out, ${Buffer.byteLength(out)} bytes`);
  }
} finally {
  fs.rmSync(dir, { recursive: true, force: true });
}
