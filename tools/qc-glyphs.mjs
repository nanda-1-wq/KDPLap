// deno run --allow-read --allow-write --allow-net tools/qc-glyphs.mjs --check  (compares, writes nothing)
// 07 Quality Control, E14.2. Makes js/qc-glyphs.js: per 08 style, the code
// points that EVERY face of the style has. The fonts are the pinned files of
// js/format/files.js, read with js/format/font-cmap.js. Each file comes from
// tests/browser/.cache/format/ when it is there, else from the CDNs, and a
// file that fails its sha384 is never used. Run once when a font pin changes.
import "../js/format/files.js";
import "../js/format/font-cmap.js";
import { encodeBase64 } from "jsr:@std/encoding@1/base64";

const F = globalThis.kdpFormatFiles;
const C = globalThis.kdpFontCmap;
const OUT = new URL("../js/qc-glyphs.js", import.meta.url);
const CACHE = new URL("../tests/browser/.cache/format/", import.meta.url);
const MAX_CP = 0x10FFFF;

async function sha384(bytes) {
  return `sha384-${encodeBase64(await crypto.subtle.digest("SHA-384", bytes))}`;
}

async function load(file) {
  const fromCache = await Deno.readFile(new URL(`${file.pkg}/${file.path}`, CACHE)).catch(() => null);
  if (fromCache && await sha384(fromCache) === file.sri) return fromCache;
  for (const url of F.urls(file)) {
    const res = await fetch(url).catch(() => null);
    if (!res || !res.ok) continue;
    const bytes = new Uint8Array(await res.arrayBuffer());
    if (await sha384(bytes) === file.sri) return bytes;
    console.error(`hash mismatch, not used: ${url}`);
  }
  throw new Error(`no good copy of ${file.pkg}/${file.path}`);
}

/** Sorted [start, end] ranges of the code points every cmap has. */
function rangesOf(cmaps) {
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= MAX_CP + 1; cp++) {
    const has = cp <= MAX_CP && cmaps.every((m) => m.has(cp));
    if (has && start < 0) start = cp;
    if (!has && start >= 0) { out.push([start, cp - 1]); start = -1; }
  }
  return out;
}

/** "gap.len,gap.len…" in base 36: gap from the last end, len = end - start. */
function encode(ranges) {
  let last = 0;
  return ranges.map(([a, b]) => {
    const s = `${(a - last).toString(36)}${b > a ? `.${(b - a).toString(36)}` : ""}`;
    last = b;
    return s;
  }).join(",");
}

const STYLE_FONT = { classic: "EB Garamond", modern: "Source Serif 4 and Source Sans 3", clean: "Literata", warm: "Lora" };

const cmapsOf = async (style) => Promise.all(F.styleFonts(style).map(async (f) => C.parse(await load(f))));
const styles = Object.keys(F.STYLE_FAMILIES);
const table = {};
const counts = {};
for (const style of styles) {
  const ranges = rangesOf(await cmapsOf(style));
  table[style] = encode(ranges);
  counts[style] = ranges.reduce((n, [a, b]) => n + b - a + 1, 0);
}

const pins = [...new Set(Object.values(F.FONTS).flat().map((f) => f.pkg))].join(", ");
const body = `/* ═══════════════════════════════════════════════════
   NicheInk · 07 Quality Control: the characters of each 08 style (E14.2)
   /js/qc-glyphs.js   (used by js/qc-rules.js; tested by tests/qc-glyphs.test.js)

   GENERATED by tools/qc-glyphs.mjs from ${pins}. Do not edit.
   Per style, the code points EVERY face of the style has, so a character
   listed here prints in regular, italic, bold and bold italic, in text and in
   titles. No font is downloaded in 07.

   kdpQcGlyphs.STYLES          → the four styles
   kdpQcGlyphs.FONT            → style → the font names, for the message
   kdpQcGlyphs.has(style, cp)  → does every face have this code point?
   Ranges: "gap.len,gap.len…" in base 36 (gap from the last end, len = end - start).
═══════════════════════════════════════════════════ */

(function (root) {
  const FONT = ${JSON.stringify(STYLE_FONT, null, 2).replace(/\n/g, "\n  ")};
  const TABLE = {
${styles.map((s) => `    ${s}: '${table[s]}'`).join(",\n")}
  };
  const STYLES = Object.keys(TABLE);
  const decoded = {};

  /** [start, end, start, end, …] of a style, read once. */
  function ranges(style) {
    if (decoded[style]) return decoded[style];
    const out = [];
    let last = 0;
    for (const part of TABLE[style].split(',')) {
      const [gap, len] = part.split('.');
      const start = last + parseInt(gap, 36);
      last = start + (len ? parseInt(len, 36) : 0);
      out.push(start, last);
    }
    return (decoded[style] = out);
  }

  function has(style, cp) {
    const r = ranges(TABLE[style] ? style : 'classic');
    let lo = 0, hi = r.length / 2 - 1;
    while (lo <= hi) {
      const mid = (lo + hi) >> 1;
      if (cp < r[mid * 2]) hi = mid - 1;
      else if (cp > r[mid * 2 + 1]) lo = mid + 1;
      else return true;
    }
    return false;
  }

  root.kdpQcGlyphs = { STYLES, FONT, has };
})(globalThis);
`;

const size = new TextEncoder().encode(body).length;
console.log(`styles: ${styles.map((s) => `${s} ${counts[s]} code points`).join(", ")}`);
console.log(`js/qc-glyphs.js: ${size} bytes${size > 15 * 1024 ? " (over the 15 KB goal)" : ""}`);
if (Deno.args.includes("--check")) {
  const now = await Deno.readTextFile(OUT);
  console.log(now === body ? "same as js/qc-glyphs.js" : "DIFFERS from js/qc-glyphs.js");
  Deno.exit(now === body ? 0 : 1);
}
await Deno.writeTextFile(OUT, body);

// Modern's table is the stricter of its two families: report what that costs.
const [serif, sans] = await Promise.all(F.STYLE_FAMILIES.modern.map((k) => Promise.all(F.FONTS[k].map(async (f) => C.parse(await load(f))))));
let bodyOnly = 0;
for (let cp = 0; cp <= MAX_CP; cp++) if (serif.every((m) => m.has(cp)) && !sans.every((m) => m.has(cp))) bodyOnly++;
console.log(`modern: ${bodyOnly} code points are in every Source Serif 4 face but not in every Source Sans 3 face`);
