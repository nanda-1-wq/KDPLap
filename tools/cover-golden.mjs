// deno run --allow-read --allow-write tools/cover-golden.mjs   (from the repo root)
// E16 Part 1: freezes the design's own answers into tests/fixtures/cover-golden.json.
// It runs the design's logic (design/screens/58-09-cover-new.html) headless; it never
// reads js/cover. Text heights are the design's own estimate (no document): the
// built code's port-proof pass uses the same estimate, so every number must match.
//   --check   compare a fresh run with the committed file (exit 1 on a difference)
import { loadDesign, designAt, DESIGN_BOOK, TRIMS, PAGES4, PAPERS } from "../tests/lib/design-cover.js";

const OUT = new URL("../tests/fixtures/cover-golden.json", import.meta.url);
const D = loadDesign();
const r4 = (v) => (typeof v === "number" ? +v.toFixed(4) : v);   // 0.0001 board px = 0.0000014 in
const round = (o) => JSON.parse(JSON.stringify(o, (k, v) => r4(v)));
const POS = ["id", "type", "src", "kind", "x", "y", "w", "h", "size", "px", "py", "pw", "ph", "rot"];
const pos = (l) => Object.fromEntries(POS.filter((k) => l[k] !== undefined).map((k) => [k, l[k]]));
const COLORS = ["color", "fill", "fill2", "scolor", "bcolor"];
const colors = (l) => Object.assign(Object.fromEntries(COLORS.filter((k) => l[k] !== undefined).map((k) => [k, l[k]])), l.fx ? { fx: l.fx.color } : {});
const chk = (c) => c.checks().map((x) => ({ sev: x.sev, msg: x.msg, id: x.id ?? null, fix: x.fix ?? null }));
const fmtKey = (f) => f.trim + "/" + f.pages + "/" + f.paper;
const keys = new D({}).LAYOUTS.map((x) => x[0]).filter((k) => k !== "blank");
const at = (fmt) => designAt(D, fmt);
const withLayout = (key, fmt) => { const c = at(fmt); const r = c.layoutLayers(key); c.state.layers = r.layers; c.state.bgColor = r.bg; c.state.nextId = r.nextId; c.state.layout = key; return c; };
const find = (c, src) => c.state.layers.find((l) => l.src === src);
const g6 = { trim: "6x9", pages: 54, paper: "white" };

export function buildGolden() {
const out = { source: "design/screens/58-09-cover-new.html", note: "Generated by tools/cover-golden.mjs. Do not edit by hand.", textH: "design estimate (0.52 em per character)" };

// 1. geometry, labels and Kindle numbers: 6 trims × 4 page counts × 2 papers
out.geo = [];
for (const trim of TRIMS) for (const pages of PAGES4) for (const paper of PAPERS) {
  const c = at({ trim, pages, paper }), g = c.geo(), v = c.renderVals();
  out.geo.push({ fmt: { trim, pages, paper }, g: Object.assign({}, g, { f: undefined }),
    labels: { trim: v.fmtTrim, pages: v.fmtPages, paper: v.fmtPaper, spine: v.fmtSpine, full: v.fmtFull, line: v.fmtLine, wrap: v.fmtWrap, px: v.fmtPx,
      fullText: v.tpl.fullText, fullMm: v.tpl.fullMm, spineText: v.tpl.spineText, spineMm: v.tpl.spineMm, spineCaps: v.tpl.spineCaps },
    kindleCut: v.kindleCut, spineNote: v.spineNote, pvKindle: v.pvKindleInner.transform, pvThumb: v.pvThumbInner.transform });
}

// 2. the 12 ready layouts × 6 trims × 54/120 pages × 2 papers (288) and Blank (24)
out.layouts = [];
out.blank = [];
for (const trim of TRIMS) for (const pages of [54, 120]) for (const paper of PAPERS) {
  const fmt = { trim, pages, paper };
  for (const key of keys) { const c = withLayout(key, fmt); out.layouts.push({ key, fmt, bg: c.state.bgColor, layers: c.state.layers.map(pos), checks: chk(c) }); }
  const b = at(fmt); b.applyLayout("blank"); const bv = b.renderVals(); out.blank.push({ fmt, checks: chk(b), chip: bv.chipLabel, summary: bv.checksSummary });
}
// the layouts' full layers once, at the authored size (every field, for the factories)
out.layoutsFull = keys.map((key) => { const c = withLayout(key, g6); return { key, bg: c.state.bgColor, nextId: c.state.nextId, layers: c.state.layers }; });

// 3. remap between sizes: 4 layouts from each trim (120 white) to each trim (240 cream), and back to 54 white
out.remap = [];
for (const key of ["band", "picfull", "stripes", "corner"]) for (const from of TRIMS) for (const to of TRIMS) {
  const A = { trim: from, pages: 120, paper: "white" }, B = { trim: to, pages: 240, paper: "cream" };
  const c = withLayout(key, A), r = c.remap(c.state.layers, c.geo(A), c.geo(B));
  out.remap.push({ key, from: A, to: B, layers: r.layers.map(pos), moved: r.moved });   // the input is out.layouts at A
}
// the size note (F72 and two more)
out.notes = [[g6, { trim: "6x9", pages: 120, paper: "white" }], [g6, { trim: "8.5x11", pages: 240, paper: "cream" }], [{ trim: "5x8", pages: 120, paper: "cream" }, { trim: "5x8", pages: 120, paper: "white" }]].map(([A, B]) => {
  const c = withLayout("band", A); c.changeFormat(B); const v = c.renderVals();
  return { from: A, to: B, text: v.fmtNoteText, sub: v.fmtNoteSub, spineNew: v.fmtSpineNew, moved: c.state.fmtNote.moved, layers: c.state.layers.map(pos) };
});

// 4. shapes: 27 kinds × 3 boxes, plus the per-shape settings
const shapeCases = [];
for (const [kind] of new D({}).SHAPES) for (const [w, h] of [[160, 160], [240, 90], [50, 300]]) shapeCases.push({ kind, w, h, radius: kind === "rounded" ? 24 : 0, points: kind === "burst" ? 14 : 5, depth: kind === "burst" ? 82 : 45, head: 40, thick: 18 });
for (const radius of [0, 8, 24, 120]) shapeCases.push({ kind: "rounded", w: 200, h: 120, radius });
for (const points of [3, 5, 12, 24]) for (const depth of [20, 45, 95]) shapeCases.push({ kind: "star", w: 180, h: 160, points, depth });
for (const head of [15, 40, 80]) shapeCases.push({ kind: "arrow", w: 240, h: 90, head });
for (const thick of [4, 18, 90]) { shapeCases.push({ kind: "frame", w: 350, h: 568, thick }); shapeCases.push({ kind: "ring", w: 200, h: 140, thick }); }
out.shapes = shapeCases.map((l) => ({ l, d: D.shapePath(l) }));
out.addShape = [];
for (const fmt of [g6, { trim: "8.5x11", pages: 240, paper: "cream" }]) for (const [kind] of new D({}).SHAPES) { const c = at(fmt); c.addShape(kind); const L = c.state.layers[0]; delete L.id; out.addShape.push({ fmt, kind, layer: L }); }

// 5. series colors: 12 layouts × 6 palettes
out.palettes = [];
for (const key of keys) for (const [name, pal] of new D({}).PALETTES) {
  const c = withLayout(key, g6); c.swapPalette(pal);
  out.palettes.push({ key, name, bg: c.state.bgColor, layers: c.state.layers.map(colors) });
}

// 6. checks: one scenario per rule (and the design's F70)
const scen = [];
const S = (name, fmt, fn) => scen.push({ name, fmt, fn });
S("F70 subtitle 6 pt, pen moved down", g6, (c) => { c.state.layers = c.state.layers.map((l) => (l.src === "subtitle" ? Object.assign({}, l, { size: 6 }) : l.src === "pen" ? Object.assign({}, l, { y: l.y + 30 }) : l)); });
S("text crossing the spine", g6, (c) => { const t = find(c, "subtitle"); t.x = 380; });
S("text outside the safe area", g6, (c) => { find(c, "title").y = 5; });
S("text near the edge", g6, (c) => { find(c, "title").y = 25; });
S("shape stops short of the edge", g6, (c) => { const s = c.state.layers.find((l) => l.type === "shape"); s.w = 420; });
S("text in the barcode box", g6, (c) => { const b = find(c, "blurb"); b.y = 520; b.x = 260; });
S("low contrast title", g6, (c) => { find(c, "title").color = "#2F4A6F"; });
S("no back text", g6, (c) => { c.state.layers = c.state.layers.filter((l) => l.src !== "blurb"); });
S("missing pen name, hidden title", g6, (c) => { c.state.layers = c.state.layers.filter((l) => l.src !== "pen"); find(c, "title").hidden = true; });
S("excluded subtitle", g6, (c) => { find(c, "subtitle").noExport = true; });
S("text on a thin spine (54 white)", g6, (c) => { c.state.layers.push(c.textLayer(99, { src: "spine", text: "MICRO STUDY HABITS", font: "IBM Plex Sans", size: 7, weight: 600, caps: true, w: 400, x: 433 - 200, y: 300, rot: 90 })); });
S("rotated title 30°", g6, (c) => { find(c, "title").rot = 30; });
S("title on a photo", g6, (c) => { const r = c.layoutLayers("picband"); c.state.layers = r.layers; c.state.bgColor = r.bg; });
S("photo full: dark 30", g6, (c) => { const r = c.layoutLayers("picfull"); c.state.layers = r.layers; c.state.bgColor = r.bg; });
for (const dpi of [150, 199, 200, 250, 299, 300]) S("picture " + dpi + " DPI", g6, (c) => { c.state.layers.unshift(Object.assign(c.imageLayer(98, { x: 500, y: 300, w: 140, h: 140, natW: Math.round(dpi * 140 / 70), natH: Math.round(dpi * 140 / 70) }))); });
S("spine text at 120 white (design 8.5 pt)", { trim: "6x9", pages: 120, paper: "white" }, (c) => { c.addSpineText(); });
S("spine text past the top", { trim: "6x9", pages: 240, paper: "white" }, (c) => { c.addSpineText(); const s = find(c, "spine"); s.w = 640; s.x = (c.geo().foldL + c.geo().foldR) / 2 - 320; });
out.checks = scen.map(({ name, fmt, fn }) => { const c = withLayout("band", fmt); c.state.layers = c.state.layers.map((l) => Object.assign({}, l)); fn(c); const v = c.renderVals(); return { name, fmt, bg: c.state.bgColor, layers: c.state.layers, checks: chk(c), chip: v.chipLabel, summary: v.checksSummary }; });

// 7. Add spine text in the design (the 6 pt rule), every trim × page count × paper where it is on
out.spineDesign = [];
for (const trim of TRIMS) for (const pages of [80, 84, 86, 100, 120, 240]) for (const paper of PAPERS) {
  const c = withLayout("band", { trim, pages, paper }); c.addSpineText(); const s = find(c, "spine");
  out.spineDesign.push({ fmt: { trim, pages, paper }, on: !!s, size: s ? s.size : null, x: s ? s.x : null, y: s ? s.y : null, w: s ? s.w : null, checks: s ? chk(c).filter((x) => x.id === s.id) : [] });
}

// 8. curved text (the design's no-document character width: 0.55 em + letter spacing)
out.curve = [];
for (const curve of [-100, -40, 25, 60, 100]) for (const [caps, ls] of [[false, 0], [true, 0.12]]) {
  const l = new D({}).textLayer(1, { text: "Micro Study Habits", x: 0, y: 0, w: 360, font: "Source Serif 4", size: 34, weight: 700, caps, ls, curve });
  const cv = new D({}).curveChars(l, {});
  out.curve.push({ l: { text: l.text, w: l.w, size: l.size, caps, ls, curve }, height: cv.height, chars: cv.list.map((x) => ({ ch: x.ch, left: x.style.left, top: x.style.top, width: x.style.width, transform: x.style.transform, origin: x.style.transformOrigin })) });
}
// 9. distortion corners and the CSS matrix
out.quad = [];
for (const dist of [{ mode: "basic", top: 0, bottom: 0 }, { mode: "basic", top: 30, bottom: -20 }, { mode: "basic", top: -50, bottom: 50 }, { mode: "free", q: [[10, 5], [-20, 0], [15, 12], [0, -8]] }, { mode: "free", q: [[0, 0], [0, 0], [0, 0], [0, 0]] }]) {
  const c = new D({}); const l = { id: 1, w: 300, dist: Object.assign({ on: true, top: 0, bottom: 0, q: [[0, 0], [0, 0], [0, 0], [0, 0]] }, dist) };
  c.hmap = { 1: 80 };
  out.quad.push({ dist: l.dist, w: 300, h: 80, q: c.quadOf(l), matrix: D.quadMatrix(300, 80, c.quadOf(l)) });
}

// 10. align, distribute, arrange (band at 6 × 9)
out.align = [];
for (const ids of [["title", "subtitle", "pen"], ["title"]]) for (const alignTo of ["sel", "front", "back", "spine", "cover"]) for (const how of ["left", "hcenter", "right", "top", "vcenter", "bottom"]) {
  const c = withLayout("band", g6); c.state.multi = ids.length > 1 ? ids.map((k) => find(c, k).id) : []; c.state.sel = ids.length > 1 ? null : find(c, ids[0]).id; c.state.alignTo = alignTo;
  c.alignMulti(how); out.align.push({ ids, alignTo, how, layers: c.state.layers.map(pos) });
}
out.distribute = ["h", "v"].map((axis) => { const c = withLayout("band", g6); c.state.multi = ["title", "subtitle", "pen", "blurb"].map((k) => find(c, k).id); c.distribute(axis); return { axis, layers: c.state.layers.map(pos) }; });
out.arrange = [];
for (const mode of ["front", "forward", "backward", "back"]) for (let i = 1; i <= 5; i++) { const c = withLayout("band", g6); c.arrange(mode, i); out.arrange.push({ mode, id: i, order: c.state.layers.map((l) => l.id) }); }

// 11. adding things
out.adds = [];
for (const fmt of [g6, { trim: "8.5x11", pages: 240, paper: "cream" }]) {
  for (const kind of ["heading", "sub", "body"]) for (let n = 0; n < 6; n++) { const c = at(fmt); c.state.layers = Array.from({ length: n }, (_, i) => ({ id: 100 + i, type: "shape", x: 0, y: 0, w: 1, h: 1 })); c.state.nextId = 7; c.addText(kind); out.adds.push({ fmt, what: "text:" + kind, n, layer: c.state.layers[c.state.layers.length - 1] }); }
  for (const key of ["title", "subtitle", "pen"]) { const c = at(fmt); c.addBook(key); out.adds.push({ fmt, what: "book:" + key, layer: c.state.layers[0] }); }
  for (const [natW, natH] of [[6000, 4000], [1600, 2400], [2000, 2000]]) { const c = at(fmt); c.addImage({ name: "p.jpg", src: "x", natW, natH, transparent: false }); const L = c.state.layers[0]; delete L.bg; out.adds.push({ fmt, what: "image:" + natW + "x" + natH, layer: L }); }
}
out.dup = (() => { const c = withLayout("band", g6); c.dupId(2); return c.state.layers.map(pos); })();
out.sizeSteps = (() => { const res = []; for (const s of [6, 7, 12, 23, 24, 25, 26, 158, 159, 160]) { const c = at(g6); c.state.layers = [c.textLayer(1, { text: "x", size: s, w: 100, x: 0, y: 0 })]; c.state.sel = 1; const v = c.renderVals(); v.sizeDown(); const down = c.state.layers[0].size; c.state.layers = [c.textLayer(1, { text: "x", size: s, w: 100, x: 0, y: 0 })]; c.renderVals().sizeUp(); res.push({ size: s, down, up: c.state.layers[0].size }); } return res; })();
out.layerNames = (() => { const c = new D({}); return [{ type: "text", text: "Short" }, { type: "text", text: "  A   long title with many words in it  " }, { type: "text", text: "" }, { type: "image", name: "desk.jpg" }, { type: "image" }, { type: "shape", kind: "burst" }, { type: "shape", kind: "nope" }, { type: "text", text: "x", label: "Mine" }].map((l) => ({ l, name: c.layerName(l) })); })();

// 12. My layouts: the design's applyMy (sample entry saved from another book, band at 6 × 9)
out.applyMy = [];
for (const fmt of [g6, { trim: "8x10", pages: 120, paper: "cream" }, { trim: "5x8", pages: 54, paper: "white" }]) {
  const c = at(fmt); const m = c.sampleMy()[0]; c.state.layers = []; c.applyMy(m);
  out.applyMy.push({ fmt, entryFmt: m.fmt, bg: c.state.bgColor, layers: c.state.layers.map((l) => Object.assign(pos(l), { text: l.text })) });
}

// 13. history: a scripted sequence with a fake clock
out.history = (() => {
  const c = withLayout("band", g6); let t = 1000; const real = Date.now; Date.now = () => t;
  const log = [];
  const step = (name, fn) => { fn(); log.push({ name, past: c.past.length, future: c.future.length, ids: c.state.layers.map((l) => l.id), bg: c.state.bgColor, titleY: (find(c, "title") || {}).y ?? null }); };
  try {
    step("move title", () => { t += 1000; c.setLayer(find(c, "title").id, { y: 200 }); });
    step("move again within 0.5 s", () => { t += 300; c.setLayer(find(c, "title").id, { y: 210 }); });
    step("sliding window", () => { t += 400; c.setLayer(find(c, "title").id, { y: 220 }); });
    step("bg after 0.6 s", () => { t += 600; c.setState({ bgColor: "#FFFFFF" }); });
    step("drag start", () => { t += 1000; c.act = { pushed: false }; c.setLayer(find(c, "title").id, { y: 230 }); });
    step("drag after 0.7 s", () => { t += 700; c.setLayer(find(c, "title").id, { y: 240 }); });
    step("drag end + delete", () => { c.act = null; t += 1000; c.removeIds([find(c, "pen").id]); });
    step("undo", () => c.undo());
    step("undo", () => c.undo());
    step("redo", () => c.redo());
    step("new change clears redo", () => { t += 1000; c.setLayer(find(c, "title").id, { y: 300 }); });
    step("undo all", () => { for (let i = 0; i < 10; i++) c.undo(); });
    for (let i = 0; i < 55; i++) { t += 1000; c.setLayer(find(c, "title").id, { y: 400 + i }); }
    step("after 55 more changes", () => {});
  } finally { Date.now = real; }
  return log;
})();

return out;
}

// one line per top-level entry and per array item, so a diff stays readable
export function serialize(out) {
const r = round(out);
const json = "{\n" + Object.keys(r).map((k) => JSON.stringify(k) + ": " + (Array.isArray(r[k]) ? "[\n" + r[k].map((x) => " " + JSON.stringify(x)).join(",\n") + "\n]" : JSON.stringify(r[k]))).join(",\n") + "\n}";
return json;
}

if (import.meta.main) {
const json = serialize(buildGolden());
if (Deno.args.includes("--check")) {
  const old = Deno.readTextFileSync(OUT);
  if (old.trim() !== json.trim()) { console.error("cover-golden.json differs from a fresh run of the design"); Deno.exit(1); }
  console.log("cover-golden.json matches the design");
} else {
  Deno.writeTextFileSync(OUT, json + "\n");
  console.log("wrote", OUT.pathname, (json.length / 1024).toFixed(0) + " KB");
}
}
